// Search function: returns matched locations sorted by relevance
export function searchIndiaLocations(query, limit = 12) {
  if (!query || query.trim().length < 1) return [];
  const q = query.trim().toLowerCase();
  const words = q.split(/\s+/).filter(Boolean);

  const results = INDIA_LOCATIONS.filter((loc) => {
    const name = loc.name.toLowerCase();
    const state = loc.state.toLowerCase();
    const type = loc.type.toLowerCase();

    // Match if name or state includes the query, or all words match either name or state
    if (name.includes(q) || state.includes(q) || type.includes(q)) return true;
    if (words.length > 1 && words.every((w) => name.includes(w) || state.includes(w))) return true;
    return false;
  });

  // Sort: exact matches first, then starts-with, then shortest name
  results.sort((a, b) => {
    const an = a.name.toLowerCase();
    const bn = b.name.toLowerCase();
    const aExact = an === q;
    const bExact = bn === q;
    if (aExact && !bExact) return -1;
    if (!aExact && bExact) return 1;

    const aStarts = an.startsWith(q);
    const bStarts = bn.startsWith(q);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;

    return an.length - bn.length;
  });

  return results.slice(0, limit);
}

